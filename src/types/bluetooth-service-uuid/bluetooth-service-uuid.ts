/**
 * A Bluetooth service UUID: a 16- or 32-bit assigned number, or a full UUID
 * string, mirroring the Web Bluetooth API `BluetoothServiceUUID` typedef used
 * by the Web Serial API.
 *
 * @see https://bluetooth.spec.whatwg.org/#typedefdef-bluetoothserviceuuid
 */
export type BluetoothServiceUUID = number | string;
